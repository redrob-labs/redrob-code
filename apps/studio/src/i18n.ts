export const dictionaries: Record<Language, Record<MessageKey, string>> = { en, ko }

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>) {
  // Keys built at runtime (a stage or status name) may not exist; show nothing rather than crash.
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? ""
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (vars && name in vars ? String(vars[name]) : match))
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export const I18nContext = createContext<Translate>((key, vars) => translate("en", key, vars))
export const useT = () => useContext(I18nContext)
